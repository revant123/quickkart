#!/usr/bin/env python3
"""Builds api/migrations/0006_india_pincodes.sql: the centre point of every Indian pincode.

Source: IndiaPIN (MIT licence, github.com/harshvardhaniimi/IndiaPIN), which packages
India Post's All India Pincode Directory (data.gov.in, Government Open Data License).

    python3 scripts/pincodes/build_pincodes.py path/to/IndiaPIN/data-raw/pincode.csv

The raw directory has one row per POST OFFICE and its coordinates are noisy (some offices
are tens of km off, some are missing or outside India). So for each pincode we:
  1. keep offices with coordinates inside India's bounding box;
  2. take the MEDIAN latitude/longitude of its offices (one bad office can't drag it);
  3. if that point is > 60 km from the median of its district, use the district median.
That is good enough to say which town a pincode is in, but can still be 10-40 km off.
  4. For pincodes near QuickKart stores, osm_points.csv (from refine_osm.py, OpenStreetMap)
     has precise points (tested 0.1-2 km off); those replace the India Post estimate and are
     marked precise. The delivery-area check only needs to be exact near stores.
"""
import csv, math, re, statistics, sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / 'api/migrations/0006_india_pincodes.sql'

def km(a, b):
    (la1, lo1), (la2, lo2) = a, b
    h = math.sin(math.radians(la2 - la1) / 2) ** 2 + math.cos(math.radians(la1)) * math.cos(math.radians(la2)) * math.sin(math.radians(lo2 - lo1) / 2) ** 2
    return 2 * 6371 * math.asin(math.sqrt(h))

def tidy_place(office):
    name = re.sub(r'\s*\b(B\.?O|S\.?O|H\.?O|G\.?P\.?O|GPO|HPO|MDG|NDG)\b\.?\s*$', '', office.strip(), flags=re.I)
    name = re.sub(r'\s+', ' ', name).strip(' .-')
    return name.title() if name.isupper() or name.islower() else name

def tidy_city(district):
    return district.strip().title().replace('&', 'and')

offices = defaultdict(list)
for r in csv.DictReader(open(sys.argv[1], encoding='utf-8', errors='replace')):
    pin = r['Pincode'].strip()
    if not re.fullmatch(r'[1-9][0-9]{5}', pin) or pin == '999999' or re.search(r'\btest\b', r['OfficeName'], re.I):
        continue  # not a real place (the directory has a 'Test Office' at 999999)
    try:
        lat, lng = float(r['Latitude']), float(r['Longitude'])
    except ValueError:
        continue
    if not (6 <= lat <= 37.5 and 68 <= lng <= 97.5):
        continue
    offices[pin].append((lat, lng, r))

points = {}
for pin, rows in offices.items():
    lat = statistics.median(x[0] for x in rows)
    lng = statistics.median(x[1] for x in rows)
    # Name the area after its head/sub office if it has one (they're in the town centre)
    main = next((x[2] for x in rows if x[2]['OfficeType'] in ('HO', 'SO')), rows[0][2])
    points[pin] = dict(lat=lat, lng=lng, area=tidy_place(main['OfficeName']),
                       city=tidy_city(main['District']), state=main['StateName'].strip().title())

by_district = defaultdict(list)
for p in points.values():
    by_district[(p['state'], p['city'])].append((p['lat'], p['lng']))
centre = {k: (statistics.median(a for a, _ in v), statistics.median(b for _, b in v)) for k, v in by_district.items()}
fixed = 0
for p in points.values():
    p['precise'] = False
    c = centre[(p['state'], p['city'])]
    if km((p['lat'], p['lng']), c) > 60:
        p['lat'], p['lng'] = c
        p['moved'] = True
        fixed += 1

refined = 0
osm_file = Path(__file__).resolve().parent / 'osm_points.csv'
if osm_file.exists():
    for r in csv.DictReader(osm_file.open()):
        p = points.get(r['pincode'])
        if not p or not r['lat']:
            continue
        osm = (float(r['lat']), float(r['lng']))
        # Trust OpenStreetMap unless it's implausibly far from the India Post estimate
        # (a different place with the same code); estimates already moved to the district
        # centre were unreliable anyway.
        if km(osm, (p['lat'], p['lng'])) <= 60 or p.get('moved'):
            p['lat'], p['lng'] = osm
            p['precise'] = True
            refined += 1

q = lambda s: "'" + s.replace("'", "''") + "'"
lines = [
    '-- 0006 India pincodes: the centre point of every pincode in India (generated by',
    '-- scripts/pincodes/build_pincodes.py from IndiaPIN, MIT licence, built on India Post\'s',
    '-- All India Pincode Directory). Lets "enter your pincode" work anywhere in the country.',
    '-- The hand-checked Chandigarh tricity points from 0004 are kept (ON CONFLICT DO NOTHING).',
    '',
    '-- precise: the point is accurate to ~2 km (OpenStreetMap near stores, or hand-checked);',
    '-- otherwise it is India Post\'s estimate, right town but possibly 10-40 km off.',
    'ALTER TABLE pincodes ADD COLUMN IF NOT EXISTS state TEXT;',
    'ALTER TABLE pincodes ADD COLUMN IF NOT EXISTS precise BOOLEAN NOT NULL DEFAULT false;',
    'UPDATE pincodes SET precise = true;  -- the hand-checked tricity rows from 0004',
    "UPDATE pincodes SET state = CASE WHEN city = 'Mohali' THEN 'Punjab' WHEN city IN ('Panchkula', 'Zirakpur') THEN 'Haryana' ELSE 'Chandigarh' END WHERE state IS NULL;",
    '',
]
items = sorted(points.items())
for i in range(0, len(items), 1000):
    chunk = items[i:i + 1000]
    lines.append('INSERT INTO pincodes (pincode, area, city, state, lat, lng, precise) VALUES')
    lines.append(',\n'.join(f"({q(pin)},{q(p['area'])},{q(p['city'])},{q(p['state'])},{p['lat']:.5f},{p['lng']:.5f},{str(p['precise']).lower()})"
                            for pin, p in chunk))
    lines.append('ON CONFLICT (pincode) DO NOTHING;')
lines.append('')
OUT.write_text('\n'.join(lines))
print(f'{len(points)} pincodes, {fixed} moved to their district centre, {refined} precise from OpenStreetMap '
      f'-> {OUT.relative_to(ROOT)} ({OUT.stat().st_size // 1024} KB)')
